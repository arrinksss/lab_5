:- initialization(solve).

слева_от(1, 2).
слева_от(2, 3).
слева_от(3, 4).
слева_от(4, 1).

справа_от(X, Y) :- слева_от(Y, X).

напротив(1, 3).
напротив(2, 4).
напротив(3, 1).
напротив(4, 2).

solve :-
    Результат = [ персона(волк, ПозВолка, фауна),
                  персона(ниф, ПозНифа, ТемаНифа),
                  персона(наф, ПозНафа, ТемаНафа),
                  персона(нуф, ПозНуфа, ТемаНуфа)
    ],
    permutation([1, 2, 3, 4], [ПозВолка, ПозНифа, ПозНафа, ПозНуфа]),
    permutation([фауна, флора, космос, спорт], [фауна, ТемаНифа, ТемаНафа, ТемаНуфа]),

    слева_от(ПозВолка, ПозНафа), 
    напротив(ПозНуфа, ПозНафа), 
    ТемаНуфа \= спорт, 

    member(персона(_, ПозКосмоса, космос), Результат), 
    справа_от(ПозНифа, ПозКосмоса), 

    forall(member(персона(Имя, Место, Тема), Результат), 
           format('~w: место ~w, марки - ~w~n', [Имя, Место, Тема])).
